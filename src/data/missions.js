// 받침 유무에 따라 을/를을 고른다.
function eulReul(word) {
  const c = word.charCodeAt(word.length - 1) - 0xac00;
  return c >= 0 && c <= 11171 && c % 28 !== 0 ? i18nT('을') : i18nT('를');
}

