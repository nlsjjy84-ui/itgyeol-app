export function playMission(game) {
  const by = PLAY_BY_MECHANIC[game.mechanic] || { mission: game.name + ' 한 판 해 보자!', steps: [] };
  return {
    kicker: i18nT('전래놀이 · {p0}', { p0: game.name }),
    title: game.name,
    story: PLAY_STORY[game.id] || game.description,
    mission: by.mission,
    steps: by.steps,
    demo: by.demo,
  };
}
