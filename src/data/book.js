// 이어서 보여 줄 때 text가 함수이면 (선택 기록)으로 풀어 준다.
export function resolveLines(lines, ctx) {
  return lines.map((l) => ({ who: l.who, text: typeof l.text === 'function' ? l.text(ctx) : l.text }));
}

