// 쓰임 한 줄(수수께끼용) — 맞는 낱말이 없으면 null
export function useOf(p) {
  if (!p) return null;
  const name = String(p.name || '').replace(/\(.*?\)/g, '');
  const hit = USE.find(([k]) => (k.length === 1 ? name.trim().endsWith(k) : new RegExp(k + '(?!\\s?(무늬|모양))').test(name)));
  return hit ? { key: hit[0], what: hit[1] } : null;
}

export function pieceStory(p) {
  if (!p) return [];
  const out = [];
  const name = String(p.name || '').replace(/\(.*?\)/g, '');
  // 한 글자 낱말은 이름 끝에서만, 「○○무늬」「○○모양」은 물건이 아니라 무늬·모양이라 건너뛴다
  const hit = USE.find(([k]) => (k.length === 1 ? name.trim().endsWith(k) : new RegExp(k + '(?!\\s?(무늬|모양))').test(name)));
  const ko = getLang() === 'ko';
  if (ko && hit) {
    // "이건 ~이야. 고려 사람들이 썼어." — 꾸밈말을 두 번 겹치지 않게 두 문장으로 나눈다
    const what = hit[1];
    const last = what.charCodeAt(what.length - 1);
    const end = /어$/.test(what) ? '.' : last >= 0xac00 && last <= 0xd7a3 && (last - 0xac00) % 28 ? '이야.' : '야.';
    out.push(`${what}${end}`);
    const made = /보살|불상|토우|잡상/.test(hit[0]) ? '만들었어' : '썼어';
    out.push(`${p.era ? josa(p.era + ' 사람들', '이/가') : '옛날 사람들이'} ${made}.`);
  } else if (p.era) {
    out.push(t('{a} 시대에 만든 유물이야.', { a: t(p.era) }));
  }
  if (p.size) {
    const s = SIZE.find(([cm]) => p.size < cm);
    out.push(t('길이는 {n}cm — {a}만 해.', { n: p.size, a: t(s[1]) }));
  }
  if (p.from) {
    const place = p.from.replace(' - ', ' ');
    out.push(t('땅속에서 찾은 곳은 {a}.', { a: getLang() === 'ko' ? josa(place, '이야/야') : place }));
  }
  if (p.abroad) out.push(t('지금은 바다 건너 {a}에 있어.', { a: t(p.by) }));
  else out.push(t('진짜는 {a}에 있어. 가서 직접 찾아봐!', { a: t(p.by) }));
  return out;
}
